MODELS_TO_TRY = ["gemini-3.6-flash", "gemini-3.1-flash-lite", "gemini-3-flash-preview"]

def call_gemini(ai_client, contents, config=None):
    """
    Calls Gemini with automatic retry and model fallback to handle
    temporary 503 UNAVAILABLE (high demand spikes) on Google servers.
    """
    last_error = None
    for model_name in MODELS_TO_TRY:
        for attempt in range(2):
            try:
                return ai_client.models.generate_content(
                    model=model_name,
                    contents=contents,
                    config=config
                )
            except Exception as e:
                last_error = e
                err_str = str(e)
                # If Google server is saturated (503 / UNAVAILABLE / high demand)
                if "503" in err_str or "UNAVAILABLE" in err_str or "high demand" in err_str:
                    time.sleep(1.5)
                    continue
                else:
                    break
    raise last_error

