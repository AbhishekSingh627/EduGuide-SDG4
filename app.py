def build_presentation(data: dict) -> bytes:
    """Builds a styled 16:9 PowerPoint presentation from structured data."""
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    PRIMARY_COLOR = RGBColor(31, 78, 121)    # #1F4E79
    DARK_TEXT = RGBColor(40, 40, 40)
    WHITE = RGBColor(255, 255, 255)

    blank_layout = prs.slide_layouts[6]

    # 1. Title Slide
    title_slide = prs.slides.add_slide(blank_layout)
    bg = title_slide.shapes.add_shape(1, Inches(0), Inches(0), Inches(13.333), Inches(7.5))
    bg.fill.solid()
    bg.fill.fore_color.rgb = PRIMARY_COLOR
    bg.line.fill.background()

    tx_box = title_slide.shapes.add_textbox(Inches(1.5), Inches(2.2), Inches(10.333), Inches(2.5))
    tf = tx_box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = data.get("title", "Quality Education (SDG 4)")
    p.font.size = Pt(42)
    p.font.bold = True
    p.font.color.rgb = WHITE
    p.alignment = PP_ALIGN.CENTER

    p2 = tf.add_paragraph()
    p2.text = data.get("subtitle", "Empowering Learners Worldwide • Generated by Edu4All")
    p2.font.size = Pt(22)
    p2.font.color.rgb = RGBColor(220, 230, 245)
    p2.alignment = PP_ALIGN.CENTER

    # 2. Content Slides
    for slide_data in data.get("slides", []):
        content_slide = prs.slides.add_slide(blank_layout)

        # Header bar
        header_bar = content_slide.shapes.add_shape(1, Inches(0), Inches(0), Inches(13.333), Inches(1.3))
        header_bar.fill.solid()
        header_bar.fill.fore_color.rgb = PRIMARY_COLOR
        header_bar.line.fill.background()

        # Slide Title
        htx = content_slide.shapes.add_textbox(Inches(0.8), Inches(0.25), Inches(11.7), Inches(0.8))
        htf = htx.text_frame
        hp = htf.paragraphs[0]
        hp.text = slide_data.get("title", "Key Insights")
        hp.font.size = Pt(30)
        hp.font.bold = True
        hp.font.color.rgb = WHITE

        # Content Bullets
        body_box = content_slide.shapes.add_textbox(Inches(1.0), Inches(1.8), Inches(11.3), Inches(4.8))
        btf = body_box.text_frame
        btf.word_wrap = True

        bullets = slide_data.get("bullets", [])
        for i, b in enumerate(bullets):
            bp = btf.paragraphs[0] if i == 0 else btf.add_paragraph()
            bp.text = f"•  {b}"
            bp.font.size = Pt(20)
            bp.font.color.rgb = DARK_TEXT
            bp.space_after = Pt(14)

        # Footer
        ftx = content_slide.shapes.add_textbox(Inches(1.0), Inches(6.8), Inches(11.3), Inches(0.5))
        fp = ftx.text_frame.paragraphs[0]
        fp.text = "UN SDG 4: Quality Education • Edu4All"
        fp.font.size = Pt(12)
        fp.font.color.rgb = RGBColor(120, 120, 120)

    buf = io.BytesIO()
    prs.save(buf)
    return buf.getvalue()

def generate_presentation_data(ai_client, topic: str, num_slides: int = 4) -> dict:
    """Uses Gemini to generate structured presentation outline in JSON with fallback."""
    prompt = f"""
    Create an educational PowerPoint presentation outline for the topic: "{topic}".
    Relate it to education, learning, or UN Sustainable Development Goal 4 (Quality Education).
    Generate exactly {num_slides} content slides.
    Return ONLY a JSON object with this exact structure:
    {{
        "title": "Presentation Title",
        "subtitle": "Informative Subtitle",
        "slides": [
            {{
                "title": "Slide Title",
                "bullets": [
                    "Concise key point 1",
                    "Concise key point 2",
                    "Concise key point 3"
                ]
            }}
        ]
    }}
    """
    response = call_gemini(
        ai_client,
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json"
        )
    )
    return json.loads(response.text)

